import {
  Component,
  ElementRef,
  Injector,
  OnDestroy,
  OnInit,
  afterNextRender,
  forwardRef,
  inject,
  viewChild,
} from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { Subscription } from 'rxjs';
import { PreprocessingService } from '../../services/preprocessing.service';
import { DataPreviewTableComponent } from '../../shared/data-preview-table/data-preview-table.component';
import { DataProfile } from '../../models/column-statistics';
import { HelpTooltipComponent } from '../../shared/help-tooltip/help-tooltip.component';
import { getStepInfo } from '../../shared/constants/step-info';
import { WizardStep, WIZARD_STEP } from '../../shared/wizard-step';
import { WizardAnnouncer } from '../../shared/wizard-announcer.service';
import { ToastService } from '../../../services/toast.service';

/** Bundled sample (generated by tools/make-sample-csv.py); relative to the app's base href. */
export const SAMPLE_DATA_URL = 'assets/samples/wine-quality-red.csv';
export const SAMPLE_FILE_NAME = 'wine-quality-red.csv';
export const SAMPLE_LOAD_ERROR = 'The sample data could not be loaded. Please try again or upload your own CSV file.';

/** Upload size limit (50 MB). */
const MAX_FILE_BYTES = 50 * 1024 * 1024;

/** Downloads the bundled sample CSV as a File, exactly like a user-picked one. */
async function fetchSampleFile(): Promise<File> {
  const response = await fetch(SAMPLE_DATA_URL);
  if (!response.ok) {
    throw new Error(`Sample data request failed (HTTP ${response.status})`);
  }
  const blob = await response.blob();
  return new File([blob], SAMPLE_FILE_NAME, { type: 'text/csv' });
}

@Component({
  selector: 'app-step1-upload',
  standalone: true,
  imports: [CommonModule, FormsModule, DataPreviewTableComponent, HelpTooltipComponent],
  templateUrl: './step1-upload.component.html',
  styleUrl: './step1-upload.component.scss',
  providers: [{ provide: WIZARD_STEP, useExisting: forwardRef(() => Step1UploadComponent) }],
})
export class Step1UploadComponent implements OnInit, OnDestroy, WizardStep {
  readonly primaryLabel = 'Continue to Column Selection';

  private subscription = new Subscription();
  private readonly announcer = inject(WizardAnnouncer);
  private readonly injector = inject(Injector);

  // Focus targets when the view swaps between the upload zone and the loaded profile
  // (the focused control is removed from the DOM in both directions).
  readonly browseButton = viewChild<ElementRef<HTMLButtonElement>>('browseButton');
  readonly profileHeading = viewChild<ElementRef<HTMLElement>>('profileHeading');

  isDragOver = false;
  isLoading = false;
  error: string | null = null;
  profile: DataProfile | null = null;

  // Expose step info to template
  readonly stepInfo = getStepInfo('upload');

  constructor(
    private preprocessingService: PreprocessingService,
    private toastService: ToastService
  ) {}

  ngOnInit(): void {
    // Subscribe to state changes to react to reset
    this.subscription.add(
      this.preprocessingService.state$.subscribe(state => {
        this.profile = state.dataProfile;
      })
    );
  }

  ngOnDestroy(): void {
    this.subscription.unsubscribe();
  }

  canProceed(): boolean {
    return this.profile !== null;
  }

  proceed(): void {
    if (this.canProceed()) {
      this.preprocessingService.nextStep();
    }
  }

  onFileSelected(event: Event): void {
    const input = event.target as HTMLInputElement;
    const file = input.files?.[0];
    // Clear the input so picking the same file again still fires (change).
    input.value = '';
    if (file) {
      void this.handleFile(file);
    }
  }

  /** "Upload Different File": back to the upload zone, focus on "Browse Files". */
  chooseDifferentFile(): void {
    this.profile = null;
    this.focusAfterRender(() => this.browseButton());
  }

  /**
   * "Try with sample data": fetches the bundled wine CSV and feeds it through
   * exactly the same path as a user upload (validation, profiling, and the
   * replace-with-undo behaviour when a file was already loaded).
   */
  async loadSampleData(): Promise<void> {
    if (this.isLoading) return;
    this.isLoading = true;
    this.error = null;
    const file = await fetchSampleFile().catch(() => null);
    if (!file) {
      this.showLoadError(SAMPLE_LOAD_ERROR);
      return;
    }
    await this.handleFile(file);
  }

  onDragOver(event: DragEvent): void {
    event.preventDefault();
    event.stopPropagation();
    this.isDragOver = true;
  }

  onDragLeave(event: DragEvent): void {
    event.preventDefault();
    event.stopPropagation();
    this.isDragOver = false;
  }

  onDrop(event: DragEvent): void {
    event.preventDefault();
    event.stopPropagation();
    this.isDragOver = false;

    const files = event.dataTransfer?.files;
    if (files && files.length > 0) {
      void this.handleFile(files[0]);
    }
  }

  private async handleFile(file: File): Promise<void> {
    const validationError = this.validateFile(file);
    if (validationError) {
      this.isLoading = false;
      this.error = validationError;
      return;
    }

    this.isLoading = true;
    this.error = null;

    // A4: if a dataset was already loaded, this upload replaces it (and its column
    // config). loadCSV snapshots the prior state, so we offer a one-click undo.
    const wasReplacement = this.preprocessingService.currentState.dataProfile !== null;

    try {
      this.profile = await this.preprocessingService.loadCSV(file);
      // Don't emit here - let user review the data first
      // User will click "Continue to Column Selection" button to emit and proceed
      // loadCSV just recorded the replacement; the toast must undo exactly that
      // entry, not whatever happens to be on top of the stack when it is clicked.
      const entryId = this.preprocessingService.latestHistoryId;
      if (wasReplacement && entryId !== null) {
        this.toastService.showUndo('File replaced', () => this.preprocessingService.undoIfLatest(entryId));
      }
      this.onProfileLoaded(this.profile);
    } catch (err: unknown) {
      this.profile = null;
      this.showLoadError(err instanceof Error ? err.message : 'Failed to load data file');
    } finally {
      this.isLoading = false;
    }
  }

  /**
   * A failed load swaps the spinner back to the upload zone; the error is read out
   * via role="alert" and focus returns to "Browse Files" to retry.
   */
  private showLoadError(message: string): void {
    this.isLoading = false;
    this.error = message;
    this.focusAfterRender(() => this.browseButton());
  }

  /** Returns a user-facing error for files the wizard cannot take, or null. */
  private validateFile(file: File): string | null {
    if (!file.name.toLowerCase().endsWith('.csv')) {
      return 'Please upload a CSV file.';
    }
    if (file.size > MAX_FILE_BYTES) {
      return 'File size exceeds 50MB limit';
    }
    return null;
  }

  /** The upload zone (and the focused control) is replaced by the profile: move focus there and announce it. */
  private onProfileLoaded(profile: DataProfile): void {
    const rows = profile.totalRows.toLocaleString('en-US');
    this.announcer.announce(`Data loaded: ${profile.fileName}, ${rows} rows, ${profile.totalColumns} columns.`);
    this.focusAfterRender(() => this.profileHeading());
  }

  private focusAfterRender(target: () => ElementRef<HTMLElement> | undefined): void {
    afterNextRender(() => target()?.nativeElement.focus(), { injector: this.injector });
  }

  get qualityClass(): string {
    if (!this.profile) return '';
    if (this.profile.qualityScore >= 90) return 'quality-excellent';
    if (this.profile.qualityScore >= 70) return 'quality-good';
    if (this.profile.qualityScore >= 50) return 'quality-fair';
    return 'quality-poor';
  }

  get qualityLabel(): string {
    if (!this.profile) return '';
    if (this.profile.qualityScore >= 90) return 'Excellent';
    if (this.profile.qualityScore >= 70) return 'Good';
    if (this.profile.qualityScore >= 50) return 'Fair';
    return 'Poor';
  }

  formatFileSize(bytes: number): string {
    if (bytes < 1024) return bytes + ' B';
    if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + ' KB';
    return (bytes / (1024 * 1024)).toFixed(1) + ' MB';
  }
}
